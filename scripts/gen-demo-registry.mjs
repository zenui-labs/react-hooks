// Generates src/components/hook-examples/registry.ts from the demo files.
// Convention: one file per hook named after the hook in kebab case,
// e.g. useLocalStorage -> use-local-storage.tsx. The slug is the name lowercased.
import {readdirSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';

const dir = join(process.cwd(), 'src/components/hook-examples');
const files = readdirSync(dir)
    .filter((f) => /^use(-[a-z0-9]+)+\.tsx$/.test(f))
    .sort();

const lines = files.map((file) => {
    const base = file.replace(/\.tsx$/, '');
    const slug = base.replace(/-/g, '');
    return `    ${slug}: dynamic(() => import('./${base}'), {ssr: false, loading: DemoLoading}),`;
});

const source = `// Generated by scripts/gen-demo-registry.mjs. Do not edit by hand.
import dynamic from 'next/dynamic';
import type {ComponentType} from 'react';
import {DemoLoading} from './loading';

export const demoRegistry: Record<string, ComponentType> = {
${lines.join('\n')}
};
`;

writeFileSync(join(dir, 'registry.ts'), source);
console.log(`registry: ${files.length} demos`);
